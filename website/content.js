export const escapeHTML = (value) =>
  String(value).replace(
    /[&<>"']/g,
    (char) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        char
      ],
  );
const e = escapeHTML;
export const brand = () =>
  '<span class="brand"><img src="./assets/postrove-mark.svg" alt="" width="30" height="30"><span>Postrove</span></span>';
const pill = (name, detail) =>
  `<span class="member"><b>${e(name)}</b><span>${e(detail)}</span></span>`;
export function members(lang) {
  return `<div class="member-list">${pill("Grok", "X")}${pill(lang === "en" ? "Diandian" : "点点", lang === "en" ? "RedNote" : "小红书")}${pill("Gemini", "YouTube")}${pill("Reddit Ask", "Reddit")}<span class="member-more" title="${e(copy[lang].more)}" aria-label="${e(copy[lang].more)}">···</span></div>`;
}
function sourceCard(c, index = 0) {
  return `<div class="source-row"><span class="source-icon">${index ? "点" : "X"}</span><div><strong>${e(index ? c.summaryTitle : c.tutorial)}</strong><small>${index ? "小红书" : "X"} · ${e(c.source)}</small></div><span class="source-arrow" aria-hidden="true">↗</span></div>`;
}
export function visual(id, lang, interactive = false) {
  const c = copy[lang];
  const question = `<div class="question-box"><div class="mentions">@Grok <span>@${lang === "en" ? "Diandian" : "点点"}</span><span>@Gemini</span><span>@Reddit Ask</span></div><p>${e(c.question)}</p><small>${e(c.mention)}</small></div>`;
  const reader = `<div class="reader-head"><span>${e(c.reading)}</span><span aria-hidden="true">↗</span></div><div class="reader-body"><small class="muted">Field Notes · ${lang === "en" ? "Sample article" : "示例文章"}</small><h3 data-reader-title>${e(c.tutorial)}</h3><div class="reader-tabs">${interactive ? `<button type="button" class="selected" data-reading="translated" aria-pressed="true">${e(c.translated)}</button><button type="button" data-reading="original" aria-pressed="false">${e(c.original)}</button>` : `<span class="selected">${e(c.translated)}</span><span>${e(c.original)}</span>`}</div><div class="summary-box"><small>${e(c.summary)}</small><p>${e(c.summaryText)}</p></div><p class="article-text" data-reader-text>${e(c.translatedText)}</p><div class="reader-foot"><span>Markdown</span><span>${e(c.source)} ↗</span></div></div>`;
  if (id === "ask") {
    const advisers = [
      ["G", "Grok", "X", c.grok],
      [
        "点",
        lang === "en" ? "Diandian" : "点点",
        lang === "en" ? "RedNote" : "小红书",
        c.diandian,
      ],
      ["G", "Gemini", "YouTube", c.gemini],
      ["R", "Reddit Ask", "Reddit", c.reddit],
    ];
    return `<div class="visual ask-visual">${question}<div class="advisor-deck"><span class="deck-back back-one" aria-hidden="true"></span><span class="deck-back back-two" aria-hidden="true"></span><div class="reply-columns">${advisers.map(([icon, name, platform, reply], index) => `<div class="reply-card"><div class="reply-head"><b class="avatar ${index ? "soft" : ""}">${e(icon)}</b><strong>${e(name)}<small>${e(platform)}</small></strong></div><p>${e(reply)}</p><div class="reply-sources"><span>${e(c.source)}</span><span aria-hidden="true">↗</span></div></div>`).join("")}</div></div><div class="deck-more"><span aria-hidden="true">···</span>${e(c.more)}</div></div>`;
  }
  if (id === "languages") {
    const routes = [
      ["中文", "用 AI 辅助读代码，有哪些实际经验？", c.languageSearchZh],
      [
        "English",
        "How do people use AI to read an unfamiliar codebase?",
        c.languageSearchEn,
      ],
    ];
    return `<div class="visual language-search-visual"><div class="language-question"><small>${e(c.languageQuestion)}</small><p>${e(c.question)}</p></div><div class="language-routes">${routes.map(([name, prompt, scope]) => `<div class="language-route"><div class="language-route-head"><b class="avatar">G</b><strong>Grok <span>${e(name)}</span></strong></div><small>${e(c.languagePromptLabel)}</small><p>${e(prompt)}</p><span class="language-scope">${e(scope)}</span></div>`).join("")}</div><div class="language-connector"><span aria-hidden="true">↓</span>${e(c.languageFlow)}</div><div class="language-answer"><div class="language-answer-heading">${e(c.languageOutput)}</div>${c.languageReplies.map((reply, i) => `<div class="language-answer-row"><strong>Grok · ${i ? "English" : "中文"}</strong><p>${e(reply)}</p></div>`).join("")}</div></div>`;
  }
  if (id === "architecture") {
    return `<div class="visual architecture-visual"><div class="architecture-app"><img src="./assets/postrove-mark.svg" alt="" width="24" height="24"><div><strong>Postrove · ${e(c.architectureApp)}</strong><small>Electron + React · ${e(c.architectureIntake)}</small></div></div><div class="architecture-pi"><div class="pi-heading"><b>Pi</b><div><strong>${e(c.architectureRuntime)}</strong><small>${e(c.architectureProviders)}</small></div></div><div class="pi-methods"><span>API Key</span><span>${e(c.architectureAuth)}</span><span>models.json</span></div></div><div class="architecture-workers">${[
      [
        c.architectureBrowser,
        c.architectureBrowserTasks,
        c.architectureBrowserTarget,
      ],
      [
        c.architectureContent,
        c.architectureContentTasks,
        c.architectureContentTarget,
      ],
    ]
      .map(
        ([name, tasks, target]) =>
          `<div class="architecture-worker"><strong>${e(name)}</strong><p>${e(tasks)}</p><small>${e(target)}</small></div>`,
      )
      .join(
        "",
      )}</div><div class="architecture-storage"><span aria-hidden="true">↓</span><div><strong>${e(c.architectureStorage)}</strong><small>${e(c.architectureFiles)}</small></div></div></div>`;
  }
  if (id === "translate")
    return `<div class="visual translation-visual"><div class="original-note"><small>${e(c.original)}</small><h4>${e(c.originalTitle)}</h4><p>${e(c.originalText)}</p></div><div class="reader-card">${reader}</div><span class="language-tag">${lang === "en" ? "中文 → English" : "English → 中文"}</span></div>`;
  if (id === "sources")
    return `<div class="visual sources-visual"><div class="source-stack"><div class="mini-heading">${lang === "en" ? "AI replies" : "顾问回答"} <span>${e(c.source)}</span></div>${sourceCard(c)}${sourceCard(c, 1)}</div><div class="collect-connector"><span>↓</span><span>${e(c.saved)}</span></div><div class="saved-card"><span class="paper-symbol">P</span><div><small>${e(c.reading)}</small><h3>${e(c.tutorial)}</h3><p>${e(c.summaryText)}</p></div><span class="saved-check">✓</span></div></div>`;
  if (id === "forward")
    return `<div class="visual forward-visual"><div class="messenger"><div class="messenger-head"><b class="avatar">P</b><div><strong>${e(c.bot)}</strong><small>Telegram / ${lang === "en" ? "Feishu" : "飞书"}</small></div></div><div class="forwarded-link"><small>${e(c.forwarded)}</small><strong>${e(c.tutorial)}</strong><span class="link-line">x.com / … / status / …</span></div></div><div class="collect-connector"><span aria-hidden="true">↓</span><span>${e(c.processing)}</span></div><div class="forward-library"><div class="library-label"><img src="./assets/postrove-mark.svg" width="20" height="20" alt=""><strong>Postrove · ${e(c.reading)}</strong><span aria-hidden="true">✓</span></div><h3>${e(c.tutorial)}</h3><p>${e(c.summaryText)}</p><div class="library-tags"><span>${e(c.readVersion)}</span><span>${e(c.summary)}</span><span>${e(c.original)}</span></div></div></div>`;
  if (id === "local")
    return `<div class="visual local-visual"><div class="files-card"><div class="mini-heading">${e(c.files)} <span>.md</span></div><div class="file-row"><b>MD</b><span>reading.md<small>${e(c.readVersion)}</small></span></div><div class="file-row"><b>MD</b><span>source.md<small>${e(c.original)}</small></span></div></div><div class="agent-card"><div class="agent-label"><span>↳</span>${e(c.agent)}</div><p>${e(c.agentPrompt)}</p><small>${e(c.agentNote)}</small></div></div>`;
  return `<div class="visual cover-visual"><div class="cover-question">${question}</div><div class="cover-reader reader-card">${reader}</div><div class="cover-members">${members(lang)}</div></div>`;
}
